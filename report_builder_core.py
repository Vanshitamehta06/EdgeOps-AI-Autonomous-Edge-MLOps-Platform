def add_body(doc, text, align=WD_ALIGN_PARAGRAPH.JUSTIFY):
    return add_styled_paragraph(doc, text, space_after=6, space_before=0, line_spacing=1.15, align=align, font_size=12)

def add_figure(doc, img_path, caption, width_in=5.5):
    if os.path.exists(img_path):
        p_img = doc.add_paragraph()
        p_img.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_img.paragraph_format.space_before = Pt(8)
        p_img.paragraph_format.space_after = Pt(4)
        run_img = p_img.add_run()
        run_img.add_picture(img_path, width=Inches(width_in))
        
        p_cap = doc.add_paragraph()
        p_cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_cap.paragraph_format.space_before = Pt(2)
        p_cap.paragraph_format.space_after = Pt(12)
        run_cap = p_cap.add_run(caption)
        run_cap.font.name = 'Times New Roman'
        run_cap.font.size = Pt(10)
        run_cap.bold = True
        run_cap.font.color.rgb = RGBColor(71, 85, 105)
    else:
        print(f"Warning: Figure not found at {img_path}")

print("Report generator framework initialized.")
