_streaming_active = False
_streaming_thread = None
_stop_reason = ""

_last_telemetry_row = {
    "Type": "M",
    "Air temperature [K]": 298.1,
    "Process temperature [K]": 308.6,
    "Rotational speed [rpm]": 1551.0,
    "Torque [Nm]": 42.8,
    "Tool wear [min]": 0.0
}

def get_last_telemetry_row():
    global _last_telemetry_row
    return dict(_last_telemetry_row)

def is_streaming(): 
    return _streaming_active

def get_stop_reason(): 
    return _stop_reason

def start_background_stream():
    global _streaming_active, _streaming_thread, _stop_reason
    if _streaming_active and _streaming_thread and _streaming_thread.is_alive():
        return True
    
    _streaming_active = True
    _stop_reason = ""
    _streaming_thread = threading.Thread(target=_stream_loop, daemon=True)
    _streaming_thread.start()
    logger.info("📡 Continuous background telemetry thread initialized and running.")
    return True

def stop_background_stream(reason="Manually Stopped"):
    global _streaming_active, _stop_reason
    if _streaming_active:
        _streaming_active = False
        _stop_reason = reason
        logger.info(f"🛑 Telemetry streaming halted. Reason: {reason}")
        return True
    return False

def _stream_loop():
    global _streaming_active, _last_telemetry_row
    if not config.DATASET_PATH.exists():
        logger.error("Cannot stream: Baseline dataset missing.")
        _streaming_active = False
        return
        
    # ==========================================
    # ANOMALY TIMELINE (10 Minute Cycle)
    # ==========================================
    CYCLE_PERIOD = 600          # 10 minutes total (600 seconds)
    NEAR_START = 540            # At 9 mins (540s): values approach thresholds (Warning phase)
    OUT_OF_BOUNDS_START = 570   # At 9.5 mins (570s): critical out-of-bounds values (Critical phase)
    
    stream_start_time = time.time()
    last_logged_minute = -1
    logger.info("🏭 Live streaming engine started (10-minute progressive degradation cycle).")
    
    while _streaming_active:
        try:
            elapsed = time.time() - stream_start_time
            cycle_progress = elapsed % CYCLE_PERIOD
            
            # Phase 1: NORMAL OPERATION (0 to 9 mins, 0 - 540s)
            if cycle_progress < NEAR_START:
                progress_ratio = cycle_progress / NEAR_START
                wear_val = 15.0 + progress_ratio * 170.0 + random.uniform(-1.0, 1.0)
                torque_val = 38.0 + progress_ratio * 6.0 + random.uniform(-1.5, 1.5)
                speed_val = 1550.0 - progress_ratio * 25.0 + random.uniform(-10.0, 10.0)
                air_temp_val = 299.5 + random.uniform(-0.5, 0.5)
                proc_temp_val = 309.5 + progress_ratio * 1.5 + random.uniform(-0.3, 0.3)
                phase_name = "Normal Operation"
                
            # Phase 2: WARNING PHASE (9 to 9.5 mins, 540 - 570s)
            elif cycle_progress < OUT_OF_BOUNDS_START:
                warn_ratio = (cycle_progress - NEAR_START) / (OUT_OF_BOUNDS_START - NEAR_START)
                wear_val = 190.0 + warn_ratio * 30.0 + random.uniform(-2.0, 2.0)
                torque_val = 55.0 + warn_ratio * 15.0 + random.uniform(-2.5, 2.5)  # approaching 70 Nm
                speed_val = 1450.0 - warn_ratio * 80.0 + random.uniform(-15.0, 15.0)
                air_temp_val = 301.0 + random.uniform(-0.5, 0.5)
                proc_temp_val = 312.5 + warn_ratio * 2.0 + random.uniform(-0.5, 0.5)
                phase_name = "Warning (Near Thresholds)"
                
            # Phase 3: CRITICAL PHASE (9.5 to 10 mins, 570 - 600s)
            else:
                crit_ratio = (cycle_progress - OUT_OF_BOUNDS_START) / (CYCLE_PERIOD - OUT_OF_BOUNDS_START)
                wear_val = 230.0 + crit_ratio * 30.0 + random.uniform(5.0, 15.0)
                torque_val = 82.0 + crit_ratio * 12.0 + random.uniform(2.0, 6.0) # > 79.8 Nm High upper limit!
                speed_val = 1250.0 - crit_ratio * 150.0 + random.uniform(-25.0, 25.0)
                air_temp_val = 304.5 + random.uniform(0.5, 2.0)
                proc_temp_val = 316.5 + random.uniform(1.0, 3.0) # > 315.9 K High limit!
                phase_name = "Critical (Out of Bounds)"
            
            # Log phase transitions to console
            current_minute = int(cycle_progress // 60)
            if current_minute != last_logged_minute:
                logger.info(f"🔄 Stream Phase: {phase_name} | Minute: {current_minute + 1}/10 | Progress: {int(cycle_progress)}s / {CYCLE_PERIOD}s")
                last_logged_minute = current_minute
            
            # Construct row dictionary matching AI4I sensor names
            row = {
                "Type": "M",
                "Air temperature [K]": round(float(air_temp_val), 2),
                "Process temperature [K]": round(float(proc_temp_val), 2),
                "Rotational speed [rpm]": round(float(speed_val), 1),
                "Torque [Nm]": round(float(torque_val), 2),
                "Tool wear [min]": round(float(wear_val), 1)
            }
            
            _last_telemetry_row = dict(row)
            
            # 1. Compare against dynamic limits in monitor_realtime
            alerts = monitor_realtime.evaluate_realtime_row(row)
            
            # Evaluate Kill Switch: if High alert, trip the system!
            for alert in alerts:
                if alert.get("level") == "High":
                    logger.warning(f"🚨 CRITICAL THRESHOLD BREACH: {alert.get('message')}")
                    stop_background_stream(reason=f"EMERGENCY SHUTDOWN: Critical limit on {alert.get('location', 'Machine')}.")
                    break
            
            # 2. Save real-time stream to SQLite so Grafana graphs and dashboard update
            if _streaming_active:
                latency_ms = 0.05
                try:
                    from edge_engine import engine
                    if engine.session is not None:
                        t_start = time.perf_counter()
                        engine.predict(row)
                        latency_ms = (time.perf_counter() - t_start) * 1000.0
                except Exception:
                    pass

                now_str = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
                
                try:
                    cpu = psutil.cpu_percent(interval=None)
                    ram = psutil.virtual_memory().percent
                except Exception:
                    cpu, ram = 25.0, 45.0
                    
                actual_drift = get_current_drift_score()
                
                if len(alerts) > 0:
                    actual_reliability = max(0.0, 100.0 - (len(alerts) * 20.0))
                else:
                    actual_reliability = 99.5
                
                try:
                    conn = sqlite3.connect(config.SQLITE_DB_PATH)
                    cursor = conn.cursor()
                    cursor.execute("SELECT current_model_id FROM deployment_state WHERE id = 1")
                    state_row = cursor.fetchone()
                    active_ver = state_row[0] if state_row and state_row[0] else 1
                    
                    cursor.execute("""
                        INSERT INTO system_metrics 
                        (model_version, cpu_usage, ram_usage, latency_ms, drift_score, reliability_score, timestamp)
                        VALUES (?, ?, ?, ?, ?, ?, ?)
                    """, (active_ver, cpu, ram, round(latency_ms, 2), actual_drift, actual_reliability, now_str))
                    conn.commit()
                    conn.close()
                except Exception as db_err:
                    logger.error(f"Failed to record system metrics in DB: {db_err}")

                time.sleep(1.0)
        except Exception as e:
            logger.error(f"Stream error: {e}")
            time.sleep(1.0)

if __name__ == "__main__":
    start_background_stream()
